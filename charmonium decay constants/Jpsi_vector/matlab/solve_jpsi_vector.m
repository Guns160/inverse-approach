function out = solve_jpsi_vector(M2min,M2max,Lambda,varargin)
%SOLVE_JPSI_VECTOR J/psi vector-current decay-constant inversion in MATLAB.
here=fileparts(mfilename('fullpath'));
addpath(fullfile(fileparts(fileparts(here)),'matlab'));
phys=struct('kind','aa','schema','jpsi-matlab-v1','S_H',13.9105153024, ...
    'has_nlo',true,'b3_cross',-11/3,'ope_order','VV n=0 LO+NLO+G2+G3', ...
    'rule','raus2024_etac_equiv_p0_1','f_field','f_jpsi', ...
    'channel_names',{{'2pole'}}, ...
    'field_names',{{'two_pole'}}, ...
    'mass_table',{{'2pole',[3.096900,3.686097]}});
out=charmonium.solveInverse(M2min,M2max,Lambda,phys,varargin{:});
end
