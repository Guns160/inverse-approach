function out = solve_eta_c_axial_vector(M2min,M2max,Lambda,varargin)
%SOLVE_ETA_C_AXIAL_VECTOR eta_c A-A decay-constant inversion in MATLAB.
here=fileparts(mfilename('fullpath'));
addpath(fullfile(fileparts(fileparts(here)),'matlab'));
phys=struct('kind','aa','schema','eta_c-aa-matlab-v1','S_H',14.99, ...
    'has_nlo',false,'b3_cross',1/3,'ope_order','AA n=0 LO+G2+G3', ...
    'rule','raus2024_etac_equiv_p0_1','f_field','f_eta_c', ...
    'channel_names',{{'2pole'}}, ...
    'field_names',{{'two_pole'}}, ...
    'mass_table',{{'2pole',[2.9841,3.51067]}});
out=charmonium.solveInverse(M2min,M2max,Lambda,phys,varargin{:});
end
