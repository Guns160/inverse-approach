function system = pp_bw_assemble(P,G,kB,g,weights,H,endpointBW,rUpper)
%PP_BW_ASSEMBLE Affine endpoint elimination; exactly two unpenalized deltas.
% c=a+E*v, L_H*E=Q*T, q=T\(Q'*L_H*a), x=[R1;R2;v+q].
% The penalty is c'*H*c = ||B*x||^2+kappa; alpha is NOT squared.
[m,N]=size(G); kB=kB(:); g=g(:); weights=weights(:); endpointBW=endpointBW(:);
assert(isequal(size(P),[m,2])&&numel(kB)==m&&numel(g)==m&&numel(weights)==m, ...
    'Invalid data/operator dimensions');
assert(isequal(size(H),[N,N])&&m>=N+1&&N>=3&&all(weights>0), ...
    'Require at least N+1 Borel data for N+1 free unknowns');
assert(numel(endpointBW)==2&&isscalar(rUpper)&& ...
    all(isfinite([P(:);G(:);kB;g;weights;H(:);endpointBW;rUpper])), ...
    'Non-finite or invalid affine input');
a=zeros(N,1); a(end)=rUpper;
d=zeros(N,1); d([1,end])=-endpointBW;
E=[d,zeros(N,N-2)]; E(2:end-1,2:end)=eye(N-2);
LH=chol(H,'upper'); LE=LH*E; [Q,T]=qr(LE,0); La=LH*a;
assert(all(diag(T)~=0)&&all(isfinite(T(:))),'rank(L_H E) must be N-1');
q=T\(Q'*La); orthogonal=La-Q*(Q'*La); kappa=orthogonal'*orthogonal;
F=[kB+G*d,G(:,2:end-1)]; sqrtw=sqrt(weights);
A=sqrtw.*[P,F]; B=[zeros(N-1,2),T]; b=sqrtw.*(g-G*a+F*q);
system=struct('P',P,'G',G,'k_B',kB,'g',g,'weights',weights,'H',H, ...
    'endpoint_bw',endpointBW,'r_upper',rUpper,'a',a,'d',d,'E',E, ...
    'L_H',LH,'Q_affine',Q,'T',T,'q',q,'kappa',kappa,'F',F, ...
    'A',A,'B',B,'b',b,'expected_p',N-1,'expected_k',2, ...
    'qr_relative_error',norm(LE-Q*T,'fro')/norm(LE,'fro'), ...
    'T_condition',cond(T));
end
