function [family,factors] = pp_bw_solve_family(system,alpha)
%PP_BW_SOLVE_FAMILY Compact GSVD of the affine problem, no alpha selection.
% MATLAB's shared GSVD convention is A=Q*U*C*X', NOT A*X=U*C.
assert(isnumeric(alpha)&&isreal(alpha)&&isvector(alpha)&&~isempty(alpha)&& ...
    all(isfinite(alpha(:)))&&all(alpha(:)>0)&&all(diff(alpha(:))>0), ...
    'Alpha must be a positive scalar or strictly increasing positive vector');
alpha=double(alpha(:).');
dec=charmonium.compactGsvd(system.A,system.B); p=system.expected_p;
assert(numel(dec.sigma)==p+2&&numel(dec.sigma_unregularized)==2, ...
    'BW compact GSVD must have exactly two unregularized modes');
beta=dec.U'*(dec.Q'*system.b);
remainder=system.b-dec.Q*(dec.U*beta);
factors=struct('sigma',dec.sigma(1:p),'mu',dec.mu(1:p), ...
    'sigma_unregularized',dec.sigma_unregularized, ...
    'sigma_tilde',dec.sigma(1:p)./dec.mu(1:p), ...
    'beta_c',beta(1:p),'beta_n',beta(p+1:end), ...
    'null',remainder'*remainder,'X',dec.X,'q',system.q,'T',system.T, ...
    'kappa',system.kappa,'data_norm',norm(sqrt(system.weights).*system.g), ...
    'n_data',numel(system.g),'n_regularized',p,'n_unregularized',2, ...
    'source',dec.source,'library',dec.library,'Q',dec.Q,'R',dec.R,'U',dec.U, ...
    'C',dec.C,'S',dec.S,'A',system.A,'B',system.B,'b0',system.b, ...
    'column_order',dec.column_order,'affine',system, ...
    'identity_relative_error_A',dec.identity_relative_error_A, ...
    'identity_relative_error_B',dec.identity_relative_error_B, ...
    'qr_relative_error',system.qr_relative_error);
den=factors.sigma.^2+factors.mu.^2.*alpha;
coef=factors.sigma.*factors.beta_c./den;
un=repmat(factors.beta_n./factors.sigma_unregularized,1,numel(alpha));
shifted=dec.X'\[coef;un];
v=shifted(3:end,:)-system.q;
c=system.a+system.E*v; residues=[shifted(1:2,:);v(1,:)];
prediction=system.P*residues(1:2,:)+system.k_B*residues(3,:)+system.G*c;
residual=prediction-system.g; weighted=system.weights.*residual;
rss=sum(system.weights.*residual.^2,1); Hc=system.H*c;
penaltySquared=sum(c.*Hc,1);
vc=system.G'*weighted+Hc.*alpha;
deltaGradient=system.P'*weighted;
bwGradient=system.k_B'*weighted+system.d'*vc;
vcScale=vecnorm(system.G'*(system.weights.*prediction),2,1)+ ...
    norm(system.G'*(system.weights.*system.g))+alpha.*vecnorm(Hc,2,1);
deltaScale=vecnorm(system.P'*(system.weights.*prediction),2,1)+ ...
    norm(system.P'*(system.weights.*system.g));
bwScale=abs(system.k_B'*(system.weights.*prediction))+ ...
    abs(system.k_B'*(system.weights.*system.g))+norm(system.d)*vcScale;
stationarity=[vecnorm(deltaGradient,2,1)./max(deltaScale,realmin); ...
    vecnorm(vc(2:end-1,:),2,1)./max(vcScale,realmin); ...
    abs(bwGradient)./max(bwScale,realmin)];
endpointError=c([1,end],:)+system.endpoint_bw*residues(3,:)-[0;system.r_upper];
assert(all(isfinite([residues(:);c(:);rss(:);penaltySquared(:);stationarity(:)])), ...
    'Non-finite BW family reconstruction or diagnostics');
family=struct('alpha',alpha,'residues_all',residues,'c_all',c, ...
    'backsub_all',prediction,'residual_all',residual, ...
    'weighted_residual_all',sqrt(rss), ...
    'relative_weighted_residual_all',sqrt(rss)/max(factors.data_norm,realmin), ...
    'penalty_all',sqrt(max(penaltySquared,0)), ...
    'objective_all',rss+alpha.*penaltySquared, ...
    'positive_all',all(residues>0,1),'endpoint_error_all',endpointError, ...
    'stationarity_relative_all',stationarity);
end
