function out = solve_eta_c_pseudoscalar(M2min,M2max,Lambda,varargin)
%SOLVE_ETA_C_PSEUDOSCALAR eta_c P-P decay-constant inversion in MATLAB.
here=fileparts(mfilename('fullpath'));
addpath(fullfile(fileparts(fileparts(here)),'matlab'));
phys=struct('kind','pp','schema','eta_c-pp-matlab-v1','S_H',14.99, ...
    'ope_order','PP n=0 LO+NLO(alpha_s)+G2+G3', ...
    'rule','raus2024_pp p.53 heuristic','f_field','f_eta_c', ...
    'channel_names',{{'2pole'}}, ...
    'field_names',{{'two_pole'}}, ...
    'mass_table',{{'2pole',[2.9841,3.6378]}});
out=charmonium.solveInverse(M2min,M2max,Lambda,phys,varargin{:});
end
