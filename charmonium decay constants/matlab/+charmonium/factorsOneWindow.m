function f = factorsOneWindow(K,g,m2,H,pab,boundary)
%FACTORSONEWINDOW Endpoint elimination and compact GSVD factors.
nFull=size(K,2); ni=size(H,1)-2;
Hii=H(2:end-1,2:end-1); Hif=H(2:end-1,[1,end]);
Rb=chol(Hii,'upper'); q=Hii\(Hif*boundary(:));
sqrtw=sqrt(charmonium.trapweights(m2));
fixed=[pab+1,nFull]; free=[1:pab,pab+2:nFull-1];
K0=sqrtw.*K(:,free);
L0=[zeros(ni,pab),Rb];
dec=charmonium.compactGsvd(K0,L0);
b0=sqrtw.*(g-K(:,fixed)*boundary(:))+K0(:,pab+1:end)*q;
betaAll=dec.U'*(dec.Q'*b0);
recon=dec.Q*dec.U*betaAll;
null2=double((b0-recon)'*(b0-recon));
nReg=ni; nUnreg=pab;
f=struct('sigma',dec.sigma(1:nReg),'mu',dec.mu(1:nReg), ...
    'sigma_unregularized',dec.sigma(end-nUnreg+1:end), ...
    'sigma_tilde',dec.sigma(1:nReg)./dec.mu(1:nReg), ...
    'beta_c',betaAll(1:nReg),'beta_n',betaAll(nReg+1:end), ...
    'null',null2,'X',dec.X,'q',q,'data_norm',norm(sqrtw.*g), ...
    'n_data',numel(g),'source',dec.source,'library',dec.library, ...
    'Q',dec.Q,'R',dec.R,'U',dec.U,'C',dec.C,'S',dec.S, ...
    'A',dec.A,'B',dec.B,'b0',b0,'column_order',dec.column_order, ...
    'identity_relative_error_A',dec.identity_relative_error_A, ...
    'identity_relative_error_B',dec.identity_relative_error_B);
assert(nReg==ni && nUnreg==pab, 'Unexpected compact-GSVD ranks');
end
