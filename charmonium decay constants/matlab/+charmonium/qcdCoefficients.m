function c = qcdCoefficients(nf, loops)
%QCDCOEFFICIENTS RunDec Eqs. (2),(7): a=alpha_s/pi, t=ln(mu^2).
% Vectors contain beta_0..beta_(loops-1), gamma_0..gamma_(loops-1).
if nargin < 2, loops = 4; end
validateattributes(nf, {'numeric'}, {'real','scalar','finite','integer','>=',1,'<=',6});
validateattributes(loops, {'numeric'}, {'real','scalar','finite','integer','>=',1,'<=',4});
n = double(nf); loops = double(loops);
z3 = 1.2020569031595942854; z4 = pi^4/90; z5 = 1.0369277551433699263;
beta = [(11-2*n/3)/4; (102-38*n/3)/16; ...
    (2857/2-5033*n/18+325*n^2/54)/64; ...
    (149753/6+3564*z3+(-1078361/162-6508*z3/27)*n ...
     +(50065/162+6472*z3/81)*n^2+1093*n^3/729)/256];
gamma = [1; (202/3-20*n/9)/16; ...
    (1249+(-2216/27-160*z3/3)*n-140*n^2/81)/64; ...
    (4603055/162+135680*z3/27-8800*z5 ...
     +(-91723/27-34192*z3/9+880*z4+18400*z5/9)*n ...
     +(5242/243+800*z3/9-160*z4/3)*n^2 ...
     +(-332/243+64*z3/27)*n^3)/256];
c = struct('beta',beta(1:loops),'gamma',gamma(1:loops), ...
    'nf',n,'loops',loops,'a_convention','alpha_s/pi','t_convention','ln(mu^2)');
end
